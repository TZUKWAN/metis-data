def _load_countries() -> tuple[dict[str, tuple[str, str]], dict[str, str]]:
    """returns (by_iso2: {upper2: (iso3, name)}, alias: {lower_alias: iso2})"""
    import pycountry

    by_iso2: dict[str, tuple[str, str]] = {}
    alias: dict[str, str] = {}
    for c in pycountry.countries:
        iso2 = c.alpha_2
        iso3 = c.alpha_3
        name = c.name
        by_iso2[iso2] = (iso3, name)
        alias[name.lower()] = iso2
        alias[iso2.lower()] = iso2
        alias[iso3.lower()] = iso2
        for attr in ("common_name", "official_name"):
            v = getattr(c, attr, None)
            if v:
                alias[v.lower()] = iso2
    for a, iso2 in _EXTRA_ALIASES.items():
        alias[a.lower()] = iso2
    # World Bank 3-letter aggregates for a few special codes are NOT countries; keep out.
    return by_iso2, alias


class CountryResolver:
    def __init__(self) -> None:
        self.by_iso2, self.alias = _load_countries()

    def resolve(self, raw: str, fuzzy_threshold: float = 0.90) -> EntityMatch | None:
        """Resolve a country string/number. ISO2/ISO3 interconvert. Original preserved by caller.

        Unknown/ambiguous values return None (caller must not silently guess, A23).
        """
        if raw is None:
            return None
        s = str(raw).strip()
        if not s:
            return None
        # numeric ISO numeric (e.g. 840 = US)
        if s.isdigit() and len(s) == 3:
            import pycountry

            try:
                c = pycountry.countries.get(numeric=s)
                if c:
                    return EntityMatch(c.alpha_2, c.name, "country", 1.0, "exact_code", s)
            except (KeyError, LookupError):
                pass
            return None
        key = s.lower()
        # exact ISO2 / ISO3
        if len(s) == 2 and s.upper() in self.by_iso2:
            iso3, name = self.by_iso2[s.upper()]
            return EntityMatch(s.upper(), name, "country", 1.0, "exact_code", s)
        if len(s) == 3 and s.upper() == s or (len(s) == 3 and s.isalpha() and s.upper() in {v[0] for v in self.by_iso2.values()}):
            up = s.upper()
            for iso2, (iso3, name) in self.by_iso2.items():
                if iso3 == up:
                    return EntityMatch(iso2, name, "country", 1.0, "exact_code", s)
        if key in self.alias:
            iso2 = self.alias[key]
            iso3, name = self.by_iso2[iso2]
            return EntityMatch(iso2, name, "country", 0.98, "alias", s)
        # fuzzy against names — but NEVER guess for aggregate/region-like strings
        # (World Bank style aggregates must stay unresolved, not silently become a country)
        aggregate_markers = (
            "&", "(", ")", "excluding", "income", "area", "region", "total", "world", "globe",
            "ida", "ibrd", "oecd", "euro ", "small states", "dividend", "fragile", "heavily",
            "least developed", "arab league", "asean", "central europe", "north america",
            "south asia", "east asia", "pacific island", "sub-saharan", "middle east",
        )
        if len(key) < 35 and not any(m in key for m in aggregate_markers):
            from difflib import SequenceMatcher

            best, best_score = None, 0.0
            for name_key, iso2 in self.alias.items():
                if not name_key.isalpha() or len(name_key) < 4 or len(name_key) >= 35:
                    continue
                if any(m in name_key for m in aggregate_markers):
                    continue
                score = SequenceMatcher(None, key, name_key).ratio()
                if score > best_score:
                    best_score, best = score, iso2
            if best and best_score >= max(fuzzy_threshold, 0.92):
                iso3, name = self.by_iso2[best]
                return EntityMatch(best, name, "country", round(best_score, 3), "fuzzy", s)
        return None

    def resolve_all(self, values: list[str], fuzzy_threshold: float = 0.90) -> dict[str, EntityMatch | None]:
        return {str(v): self.resolve(v, fuzzy_threshold) for v in values}

    def to_iso3(self, iso2: str) -> str:
        return self.by_iso2[iso2][0]


