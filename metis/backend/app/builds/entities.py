class ChinaRegionResolver:
    def __init__(self) -> None:
        self.provinces: dict[str, tuple[str, int, str]] = {code: (name, vf, vt) for code, name, vf, vt in CN_PROVINCES}
        self.prefectures: dict[str, tuple[str, str, int, str]] = {code: (name, parent, vf, vt) for code, name, parent, vf, vt in CN_PREFECTURES}
        self.name_to_code: dict[str, str] = {name: code for code, name, _vf, _vt in CN_PROVINCES}
        self.name_to_code.update(CN_PROVINCE_ALIASES)
        self.pref_name_to_code: dict[str, str] = {name: code for code, name, _p, _vf, _vt in CN_PREFECTURES}
        self.historical: dict[str, list[tuple[str, int, str]]] = {}
        for code, name, vf, vt in CN_HISTORICAL:
            if name:
                self.historical.setdefault(code, []).append((name, vf, vt))

    def resolve_province(self, raw: str, year: int | None = None) -> EntityMatch | None:
        s = str(raw).strip()
        if not s:
            return None
        if s.isdigit() and s in self.provinces:
            name, vf, vt = self.provinces[s]
            if year and vt and int(year) > int(vt):
                return None  # entity did not exist then; do not map silently
            return EntityMatch(s, name, "china_province", 1.0, "exact_code", s)
        code = self.name_to_code.get(s)
        if code is None and s.endswith(("省", "市")):
            code = self.name_to_code.get(s[:-1])
        if code:
            name, vf, vt = self.provinces[code]
            if year and (int(year) < int(vf) or (vt and int(year) > int(vt))):
                return None
            return EntityMatch(code, name, "china_province", 1.0, "exact_name", s)
        from difflib import SequenceMatcher

        best, score = None, 0.0
        for name in self.provinces.values():
            sc = SequenceMatcher(None, s, name[0]).ratio()
            if sc > score:
                score, best = sc, name[0]
        if best and score >= 0.87:
            code = self.name_to_code[best]
            return EntityMatch(code, best, "china_province", round(score, 3), "fuzzy", s)
        return None

    def resolve_prefecture(self, raw: str, year: int | None = None) -> EntityMatch | None:
        s = str(raw).strip()
        if not s:
            return None
        if s.isdigit() and s in self.prefectures:
            name, parent, vf, vt = self.prefectures[s]
            if year and vt and int(year) > int(vt):
                return None
            return EntityMatch(s, name, "china_prefecture", 1.0, "exact_code", s)
        code = self.pref_name_to_code.get(s)
        if code is None and s.endswith("市"):
            code = self.pref_name_to_code.get(s)
        if code is None:
            stripped = s[:-1] if s.endswith("市") else s
            code = self.pref_name_to_code.get(stripped + "市")
        if code:
            name, parent, vf, vt = self.prefectures[code]
            if year and (int(year) < int(vf) or (vt and int(year) > int(vt))):
                return None
            # historical note preserved
            hist = self.historical.get(code, [])
            conf = 1.0
            return EntityMatch(code, name, "china_prefecture", conf, "exact_name" + ("+historical" if hist else ""), s)
        return None

    def historical_names(self, code: str) -> list[tuple[str, int, str]]:
        return self.historical.get(code, [])
